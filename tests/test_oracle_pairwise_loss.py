        self.assertIn("0.3", summary)
        self.assertEqual(payload["recomputed"]["mean_loss_a_exact"], "3/10")
        self.assertEqual(payload["report_rounding"]["mode"], "half_even")
        self.assertNotIn(",", payload["recomputed"]["mean_loss_a"])

