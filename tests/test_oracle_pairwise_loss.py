# Hand calculation for example.csv. Do not replace these with verifier output.
# mean_a = (0.20 + 0.40 + 0.30) / 3 = 0.90 / 3 = 0.30
# mean_b = (0.30 + 0.35 + 0.40) / 3 = 1.05 / 3 = 0.35
# delta  = ((0.20-0.30) + (0.40-0.35) + (0.30-0.40)) / 3
#        = (-0.10 + 0.05 + -0.10) / 3 = -0.15 / 3 = -0.05
EXAMPLE_MEAN_A = (Fraction("0.20") + Fraction("0.40") + Fraction("0.30")) / 3
EXAMPLE_MEAN_B = (Fraction("0.30") + Fraction("0.35") + Fraction("0.40")) / 3
EXAMPLE_DELTA = (
    (Fraction("0.20") - Fraction("0.30"))
    + (Fraction("0.40") - Fraction("0.35"))
    + (Fraction("0.30") - Fraction("0.40"))
) / 3
SWAPPED_MEAN_A = EXAMPLE_MEAN_B
SWAPPED_MEAN_B = EXAMPLE_MEAN_A
SWAPPED_DELTA = -EXAMPLE_DELTA


def within_tol(declared: Fraction, recomputed: Fraction,
               abs_tol: Fraction, rel_tol: Fraction) -> bool:
    """Contract §3.1, copied here so expected matches are not generated
    by the function under test."""
    return abs(declared - recomputed) <= abs_tol + rel_tol * abs(recomputed)


def conclusion_from_contract(delta: Fraction, tau: Fraction) -> str:
    """Copy of the contract rule, kept here so expected verdicts are not
    generated by the function under test."""
    if abs(delta) <= tau:
        return "equivalent_within_tolerance"
    if delta < 0:
        return "A_lower"
    return "B_lower"


def status(report, check_id: str) -> str:
    return next(c.status for c in report.checks if c.id == check_id)


def reason(report, check_id: str) -> str:
    return next(c.reason for c in report.checks if c.id == check_id)


def run(csv_name: str, candidate_name: str, config_name: str | None = "config_default.json"):
    config = None if config_name is None else FIXTURES / config_name
    return verify_paths(FIXTURES / csv_name, FIXTURES / candidate_name, config)


class HandCalculationTests(unittest.TestCase):
    """The known results exist before the verifier is asked anything."""

    def test_example_means_are_exact_tenths(self):
        self.assertEqual(EXAMPLE_MEAN_A, Fraction(3, 10))
        self.assertEqual(EXAMPLE_MEAN_B, Fraction(7, 20))
        self.assertEqual(EXAMPLE_DELTA, Fraction(-1, 20))
        self.assertEqual(EXAMPLE_MEAN_A - EXAMPLE_MEAN_B, EXAMPLE_DELTA)

    def test_swapped_means(self):
        self.assertEqual(SWAPPED_MEAN_A, Fraction(7, 20))
        self.assertEqual(SWAPPED_MEAN_B, Fraction(3, 10))
        self.assertEqual(SWAPPED_DELTA, Fraction(1, 20))

    def test_boundary_rule_is_closed_interval(self):
        tau = Fraction("0.05")
        self.assertEqual(conclusion_from_contract(Fraction("-0.05"), tau),
                         "equivalent_within_tolerance")
        self.assertEqual(conclusion_from_contract(Fraction("0.05"), tau),
                         "equivalent_within_tolerance")
        self.assertEqual(conclusion_from_contract(Fraction("-0.0500001"), tau), "A_lower")
        self.assertEqual(conclusion_from_contract(Fraction("0.0500001"), tau), "B_lower")
        self.assertEqual(conclusion_from_contract(Fraction("-0.049"), tau),
                         "equivalent_within_tolerance")
        self.assertEqual(conclusion_from_contract(Fraction(0), Fraction(0)),
                         "equivalent_within_tolerance")
        self.assertEqual(conclusion_from_contract(Fraction("-0.01"), Fraction(0)), "A_lower")


